#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import prettier from "prettier";

const ROOT = new URL("../", import.meta.url);

const FIXTURES = {
  statusline: new URL("testdata/contracts/v1/statusline/model.json", ROOT),
  attachments: new URL("testdata/contracts/v1/attachments/text.json", ROOT),
  coordination: new URL("testdata/contracts/v1/coordination/model.json", ROOT),
  alerts: new URL("testdata/contracts/v1/alerts/display.json", ROOT),
};

const hash = (value) => createHash("sha256").update(JSON.stringify(value)).digest("hex");

const writeContractJson = async (url, contract) => {
  await mkdir(new URL("./", url), { recursive: true });
  const prettierOptions = (await prettier.resolveConfig(url.pathname)) ?? {};
  await writeFile(url, await prettier.format(JSON.stringify(contract), { ...prettierOptions, parser: "json" }));
};

const recordCase = (idPrefix, index, name, source, api, input, output) => ({
  id: `${idPrefix}-${String(index + 1).padStart(3, "0")}`,
  name,
  source,
  api,
  input,
  output: output === undefined ? null : output,
  inputSha256: hash(input),
});

const statusline = await import(new URL("dist/statusline-model.js", ROOT));
const attachments = await import(new URL("dist/attachment-text.js", ROOT));
const coordination = await import(new URL("dist/coordination-model.js", ROOT));
const alerts = await import(new URL("dist/alert-display.js", ROOT));

