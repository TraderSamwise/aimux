function normalize(value, roots = {}) {
  const ids = new Map();
  const tokenFor = (id) => {
    if (!ids.has(id)) ids.set(id, `<att:${ids.size + 1}>`);
    return ids.get(id);
  };
  return JSON.parse(
    JSON.stringify(value, (key, nested) => {
      if (typeof nested !== "string") return nested;
      if (key === "createdAt") return "<createdAt>";
      let text = nested;
      for (const [label, root] of Object.entries(roots)) text = text.replaceAll(root, `<${label}>`);
      text = text.replace(/att_[0-9a-f]{32}/g, (id) => tokenFor(id));
      return text;
    }),
  );
}

function runCatching(fn, roots) {
  try {
    return normalize({ ok: true, value: fn() }, roots);
  } catch (error) {
    return normalize({ ok: false, error: error instanceof Error ? error.message : String(error) }, roots);
  }
}

async function withProject(prefix, fn) {
  const repoRoot = mkdtempSync(join(tmpdir(), `${prefix}-repo-`));
  const previousHome = process.env.AIMUX_HOME;
  process.env.AIMUX_HOME = mkdtempSync(join(tmpdir(), `${prefix}-home-`));
  mkdirSync(join(repoRoot, ".git"), { recursive: true });
  await paths.initPaths(repoRoot);
  try {
    return await fn(repoRoot, { project: repoRoot, temp: tmpdir() });
  } finally {
    store.forgetSessionAttachments();
    rmSync(repoRoot, { recursive: true, force: true });
    rmSync(process.env.AIMUX_HOME, { recursive: true, force: true });
    if (previousHome === undefined) delete process.env.AIMUX_HOME;
    else process.env.AIMUX_HOME = previousHome;
  }
}

function snapshotAttachment(id, sessionId, roots) {
  const record = store.getAttachmentRecord(id, sessionId);
  const content = store.getAttachmentContent(id, sessionId);
  return normalize(
    {
      record,
      contentUtf8: content?.buffer.toString("utf8") ?? null,
      contentMimeType: content?.mimeType ?? null,
    },
    roots,
  );
}

